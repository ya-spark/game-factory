#!/usr/bin/env python3
"""Writes the web shell of one game (web/index.html, web/manifest.json) from its app.config.yaml.

Usage: python3 scripts/web_shell.py <app_dir> [--check]   (the copy in each game repo and in the template)

Reads: app.display_name, theme.seed_color, web.description, web.indexable, web.play_store_url.
Writes a real page title and description, theme colour, social preview tags (title, description,
the 192px icon), a calm loading screen that goes away on the first Flutter frame, a favicon and
manifest name, and `noindex, nofollow` unless `web.indexable: true`. The "Get the Android app" link
is on the loading screen only when `web.play_store_url` is set. Idempotent: a second run changes
nothing. `--check` writes nothing and exits 1 when a file would change (used by CI and the tests).
No ad code and no third-party script: the page loads only the Flutter bundle.

Needs PyYAML-free parsing on purpose (the script runs in plain Python): it reads the few keys it
needs with a tiny line parser, see `read_config`.
"""
from __future__ import annotations

import argparse
import html
import json
import re
import sys
from pathlib import Path

DEFAULT_DESCRIPTION = "A free game that saves your progress in your browser."


def _scalar(v: str) -> str:
    v = v.split(" #")[0].strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        v = v[1:-1]
    return v


def read_config(text: str) -> dict:
    """Reads app.display_name, theme.seed_color and the web: block (two-space indented scalars)."""
    out = {"display_name": "", "seed_color": "#2EC4B6", "description": "", "indexable": False, "play_store_url": ""}
    section = None
    for raw in text.splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        m = re.match(r"^([A-Za-z_]+):\s*(.*)$", raw)
        if m:
            section = m.group(1)
            continue
        m = re.match(r"^  ([A-Za-z_]+):\s*(.*)$", raw)
        if not m or section is None:
            continue
        key, val = m.group(1), _scalar(m.group(2))
        if section == "app" and key == "display_name":
            out["display_name"] = val
        elif section == "theme" and key == "seed_color":
            out["seed_color"] = val
        elif section == "web":
            if key == "description":
                out["description"] = val
            elif key == "indexable":
                out["indexable"] = val.lower() == "true"
            elif key == "play_store_url":
                out["play_store_url"] = val
    if not out["display_name"]:
        raise SystemExit("web_shell: app.display_name missing in app.config.yaml")
    return out


def render_index(c: dict) -> str:
    e = lambda s: html.escape(s, quote=True)  # noqa: E731
    name = e(c["display_name"])
    desc = e(c["description"] or DEFAULT_DESCRIPTION)
    color = e(c["seed_color"])
    robots = "index, follow" if c["indexable"] else "noindex, nofollow"
    link = ""
    if c["play_store_url"]:
        link = f'\n    <a class="get" href="{e(c["play_store_url"])}" rel="noopener">Get the Android app</a>'
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <!-- Generated by scripts/web_shell.py from app.config.yaml. Edit the config, not this file. -->
  <!-- The web copy is built with --base-href /<app-folder>/ (see docs/DEPLOY-TO-VPS-AS-WEB.md in game-studio). -->
  <base href="$FLUTTER_BASE_HREF">

  <meta charset="UTF-8">
  <meta content="IE=Edge" http-equiv="X-UA-Compatible">
  <meta name="viewport" content="width=device-width, initial-scale=1.0, user-scalable=no">
  <title>{name}</title>
  <meta name="description" content="{desc}">
  <meta name="theme-color" content="{color}">
  <meta name="robots" content="{robots}">

  <!-- Social preview -->
  <meta property="og:type" content="website">
  <meta property="og:title" content="{name}">
  <meta property="og:description" content="{desc}">
  <meta property="og:image" content="icons/Icon-192.png">
  <meta name="twitter:card" content="summary">
  <meta name="twitter:title" content="{name}">
  <meta name="twitter:description" content="{desc}">
  <meta name="twitter:image" content="icons/Icon-192.png">

  <!-- iOS meta tags & icons -->
  <meta name="mobile-web-app-capable" content="yes">
  <meta name="apple-mobile-web-app-status-bar-style" content="black">
  <meta name="apple-mobile-web-app-title" content="{name}">
  <link rel="apple-touch-icon" href="icons/Icon-192.png">

  <!-- Favicon and manifest -->
  <link rel="icon" type="image/png" href="favicon.png"/>
  <link rel="manifest" href="manifest.json">

  <style>
    html, body {{ margin: 0; height: 100%; background: #101820; }}
    #loading {{
      position: fixed; inset: 0; display: flex; flex-direction: column; align-items: center;
      justify-content: center; gap: 16px; background: #101820; color: #fff;
      font-family: system-ui, sans-serif; text-align: center; transition: opacity .4s;
    }}
    #loading img {{ width: 96px; height: 96px; border-radius: 22px; }}
    #loading h1 {{ margin: 0; font-size: 22px; font-weight: 700; }}
    #loading p {{ margin: 0; opacity: .7; font-size: 14px; }}
    #loading .get {{ color: {color}; font-size: 14px; }}
    #loading .bar {{ width: 120px; height: 4px; border-radius: 2px; background: #ffffff22; overflow: hidden; }}
    #loading .bar::after {{
      content: ""; display: block; width: 40%; height: 100%; background: {color};
      animation: slide 1.4s ease-in-out infinite;
    }}
    @keyframes slide {{ from {{ margin-left: -40%; }} to {{ margin-left: 100%; }} }}
  </style>
</head>
<body>
  <div id="loading">
    <img src="icons/Icon-192.png" alt="">
    <h1>{name}</h1>
    <div class="bar"></div>
    <p>Getting ready...</p>{link}
  </div>
  <script>
    window.addEventListener('flutter-first-frame', function () {{
      var el = document.getElementById('loading');
      if (!el) return;
      el.style.opacity = '0';
      setTimeout(function () {{ el.remove(); }}, 450);
    }});
  </script>
  <script src="flutter_bootstrap.js" async></script>
</body>
</html>
"""


def render_manifest(c: dict) -> str:
    m = {
        "name": c["display_name"],
        "short_name": c["display_name"],
        "start_url": ".",
        "display": "standalone",
        "background_color": "#101820",
        "theme_color": c["seed_color"],
        "description": c["description"] or DEFAULT_DESCRIPTION,
        "orientation": "portrait-primary",
        "prefer_related_applications": False,
        "icons": [
            {"src": "icons/Icon-192.png", "sizes": "192x192", "type": "image/png"},
            {"src": "icons/Icon-maskable-192.png", "sizes": "192x192", "type": "image/png", "purpose": "maskable"},
        ],
    }
    return json.dumps(m, indent=4, ensure_ascii=False) + "\n"


def write_shell(app_dir: Path, check: bool = False) -> list[str]:
    """Writes (or with check=True only compares) the files; returns the names that differ."""
    cfg = read_config((app_dir / "app.config.yaml").read_text(encoding="utf-8"))
    web = app_dir / "web"
    web.mkdir(exist_ok=True)
    changed = []
    for name, text in (("index.html", render_index(cfg)), ("manifest.json", render_manifest(cfg))):
        f = web / name
        if not f.is_file() or f.read_text(encoding="utf-8") != text:
            changed.append(name)
            if not check:
                f.write_text(text, encoding="utf-8")
    return changed


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("app_dir")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    changed = write_shell(Path(a.app_dir), check=a.check)
    if a.check:
        if changed:
            print(f"web shell out of date: {', '.join(changed)} (run scripts/web_shell.py)", file=sys.stderr)
            return 1
        print("web shell up to date")
        return 0
    print("updated: " + ", ".join(changed) if changed else "web shell up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
