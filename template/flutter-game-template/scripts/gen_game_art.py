#!/usr/bin/env python3
"""Turns design/game_art/<game id>.svg into lib/ui/kit/game_art_data.dart (the `gameArtData` map).

The SVG files are the single source; the Dart file is generated and never edited by hand.
Run from the repo root:  python3 scripts/gen_game_art.py          (write)
                         python3 scripts/gen_game_art.py --check  (exit 1 if out of date)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# The template keeps the source in design/game_art; a generated game gets it as tool/game_art.
SRC = next((d for d in (ROOT / "design" / "game_art", ROOT / "tool" / "game_art") if d.is_dir()), ROOT / "design" / "game_art")
OUT = ROOT / "lib" / "ui" / "kit" / "game_art_data.dart"


def render() -> str:
    files = sorted(SRC.glob("*.svg"))
    if not files:
        raise SystemExit(f"no SVG files in {SRC}")
    lines = [
        "// GENERATED by scripts/gen_game_art.py from design/game_art/*.svg (tool/game_art in a game). Do not edit by hand.",
        "// ignore_for_file: lines_longer_than_80_chars",
        "",
        "/// Game id to full-colour tile art (96 by 96 SVG, own background, no `currentColor`).",
        "const Map<String, String> gameArtData = {",
    ]
    for f in files:
        svg = " ".join(f.read_text(encoding="utf-8").split())
        if "'''" in svg or "currentColor" in svg:
            raise SystemExit(f"{f.name}: not allowed in tile art")
        lines.append(f"  '{f.stem}': r'''{svg}''',")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("game_art_data.dart is out of date: run python3 scripts/gen_game_art.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
