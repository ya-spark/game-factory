/// Difficulty tiers (docs/SPEC.md, 4.5): the layouts on offer and how many hints and shuffles a
/// game allows (null = unlimited). A hint still costs 40 points and a shuffle 80.
enum MahjongTier {
  easy('Easy', null, null),
  medium('Medium', 3, 2),
  hard('Hard', 3, 1),
  expert('Expert', 1, 1);

  const MahjongTier(this.label, this.hintLimit, this.shuffleLimit);
  final String label;
  final int? hintLimit;
  final int? shuffleLimit;

  /// The layouts of this tier: the first nine for Easy and Medium, new ones for Hard and Expert.
  List<MahjongLayout> get layouts => switch (this) {
    easy || medium => mahjongLayouts,
    hard => mahjongHardLayouts,
    expert => mahjongExpertLayouts,
  };

  static MahjongTier? byName(String? name) {
    for (final t in values) {
      if (t.name == name) return t;
    }
    return null;
  }
}

bool _overlap(MjPos a, MjPos b) =>
    (a.x - b.x).abs() < 2 && (a.y - b.y).abs() < 2;

/// Whether tile [i] of [pos] is free among the tiles still in [alive]: nothing lies on it, and
/// its left or its right side is open.
bool isFreeIn(List<MjPos> pos, bool Function(int) alive, int i) {
  final p = pos[i];
  var left = false, right = false;
  for (var j = 0; j < pos.length; j++) {
    if (j == i || !alive(j)) continue;
    final q = pos[j];
    if (q.z == p.z + 1 && _overlap(p, q)) return false;
    if (q.z == p.z && (q.y - p.y).abs() < 2) {
      if (q.x == p.x - 2) left = true;
      if (q.x == p.x + 2) right = true;
    }
  }
  return !(left && right);
}

/// Gives faces to the tiles in [tiles] (indexes into [pos]) so that they can all be taken off in
/// pairs, one free pair after the other. Returns null when the construction got stuck (the caller
/// tries again with the next random draw).
Map<int, int>? dealFaces(List<MjPos> pos, List<int> tiles, Random rnd) {
  if (tiles.length.isOdd) return null;
  final alive = {...tiles};
  final deck = <int>[];
  while (deck.length < tiles.length ~/ 2) {
    final d = List.generate(faceCount, (i) => i)..shuffle(rnd);
    deck.addAll(d);
  }
  final faces = <int, int>{};
  var pair = 0;
  while (alive.isNotEmpty) {
    final free = [
      for (final i in alive)
        if (isFreeIn(pos, alive.contains, i)) i,
    ];
    if (free.length < 2) return null;
    final a = free.removeAt(rnd.nextInt(free.length));
    final b = free.removeAt(rnd.nextInt(free.length));
    faces[a] = faces[b] = deck[pair++];
    alive
      ..remove(a)
      ..remove(b);
  }
  return faces;
}

/// Deals [layout]: a face for each place, solvable by construction.
List<int> dealLayout(MahjongLayout layout, Random rnd) {
  final all = List.generate(layout.positions.length, (i) => i);
  for (var tries = 0; tries < 500; tries++) {
    final f = dealFaces(layout.positions, all, rnd);
    if (f != null) return [for (var i = 0; i < all.length; i++) f[i]!];
  }
  throw StateError('No deal found for ${layout.name}');
}

/// A game in progress.
class MahjongGame {
  MahjongGame(
    this.layout,
    Random rnd, {
    List<int>? faces,
    this.tier = MahjongTier.easy,
  }) : _rnd = rnd,
       faces = faces ?? dealLayout(layout, rnd),
       _removed = List.filled(layout.positions.length, false);

  final MahjongLayout layout;
  final MahjongTier tier;
  final Random _rnd;
  final List<int> faces;
  final List<bool> _removed;
  final List<(int, int)> _undo = [];
  int hints = 0;
  int shuffles = 0;
  int pairsTaken = 0;

  /// Zen (M5): hints and shuffles never run out. Set by the screen for the run; never saved.
  bool unlimited = false;

  List<MjPos> get positions => layout.positions;
  bool removed(int i) => _removed[i];
  int get remaining => _removed.where((r) => !r).length;
  bool get won => remaining == 0;
  bool get canUndo => _undo.isNotEmpty;

  bool isFree(int i) =>
      !_removed[i] && isFreeIn(positions, (j) => !_removed[j], i);

  /// True when [a] and [b] are two different free tiles with the same face.
  bool canMatch(int a, int b) =>
      a != b && isFree(a) && isFree(b) && faces[a] == faces[b];

  /// Every free pair that can be taken now.
  List<(int, int)> moves() {
    final free = [
      for (var i = 0; i < faces.length; i++)
        if (isFree(i)) i,
    ];
    return [
      for (var x = 0; x < free.length; x++)
        for (var y = x + 1; y < free.length; y++)
          if (faces[free[x]] == faces[free[y]]) (free[x], free[y]),
    ];
  }

  bool get stuck => !won && moves().isEmpty;

  /// Takes the pair off. Returns false when it is not a free matching pair.
  bool take(int a, int b) {
    if (!canMatch(a, b)) return false;
    _removed[a] = _removed[b] = true;
    _undo.add((a, b));
    pairsTaken++;
    return true;
  }

  /// Puts the last pair back. Returns false when there is nothing to undo.
  bool undo() {
    if (_undo.isEmpty) return false;
    final (a, b) = _undo.removeLast();
    _removed[a] = _removed[b] = false;
    pairsTaken--;
    return true;
  }

  /// Hints left in this tier (null = unlimited).
  int? get hintsLeft {
    final l = unlimited ? null : tier.hintLimit;
    return l == null ? null : max(0, l - hints);
  }

  /// Shuffles left in this tier (null = unlimited).
  int? get shufflesLeft {
    final l = unlimited ? null : tier.shuffleLimit;
    return l == null ? null : max(0, l - shuffles);
  }

  bool get canHint => (hintsLeft ?? 1) > 0;
  bool get canShuffle => (shufflesLeft ?? 1) > 0;

  /// A pair to show, or null when stuck or no hint is left. Counts against the score.
  (int, int)? hint() {
    if (!canHint) return null;
    final m = moves();
    if (m.isEmpty) return null;
    hints++;
    return m.first;
  }

  /// Deals the faces of the tiles still on the table again. The new deal is solvable by
  /// construction from this position when the position allows it; otherwise the faces are mixed
  /// until at least one pair can be taken. Undo history is cleared. Returns false when no tiles
  /// remain.
  bool shuffle() {
    if (!canShuffle) return false;
    final left = [
      for (var i = 0; i < faces.length; i++)
        if (!_removed[i]) i,
    ];
    if (left.isEmpty) return false;
    final old = [for (final i in left) faces[i]];
    Map<int, int>? deal;
    for (var t = 0; t < 200 && deal == null; t++) {
      deal = dealFaces(positions, left, _rnd);
    }
    if (deal != null) {
      for (final i in left) {
        faces[i] = deal[i]!;
      }
    } else {
      for (var t = 0; t < 200; t++) {
        final mixed = List.of(old)..shuffle(_rnd);
        for (var k = 0; k < left.length; k++) {
          faces[left[k]] = mixed[k];
        }
        if (moves().isNotEmpty) break;
      }
    }
    shuffles++;
    _undo.clear();
    return true;
  }

  /// Score of a cleared table: 50 per pair + 100, minus 40 per hint and 80 per shuffle, at
  /// least 50.
  int get score =>
      max(50, layout.pairs * 50 + 100 - hints * 40 - shuffles * 80);
}
