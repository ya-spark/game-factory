/// Mahjong solitaire rules: layouts of stacked tiles, free tiles, matching pairs, undo, hint and
/// shuffle. Every deal is solvable by construction: faces are given to pairs of tiles in the
/// order the pairs can be taken off the layout. Pure Dart (no Flutter, Flame or Android imports).
/// The random source is injected.
library;

import 'dart:math';

/// Suits of the tiles (original names and shapes, not mahjong suits).
const int suitCount = 4;

/// Ranks per suit (1 to 6 pips).
const int rankCount = 6;

/// Different faces: suit x rank.
const int faceCount = suitCount * rankCount;

int suitOf(int face) => face ~/ rankCount;
int rankOf(int face) => face % rankCount + 1;

/// One place for a tile. [x] and [y] are in half tiles (a tile is 2 x 2); [z] is the layer.
class MjPos {
  const MjPos(this.x, this.y, this.z);
  final int x, y, z;
}

/// A named layout of tile places (always an even number).
class MahjongLayout {
  const MahjongLayout(this.name, this.positions);
  final String name;
  final List<MjPos> positions;

  int get pairs => positions.length ~/ 2;
  int get maxX => positions.map((p) => p.x).reduce(max);
  int get maxY => positions.map((p) => p.y).reduce(max);
  int get maxZ => positions.map((p) => p.z).reduce(max);
}

/// A block of [cols] x [rows] tiles whose top-left tile is at ([col], [row]) in whole tiles.
List<MjPos> _rect(
  int col,
  int row,
  int cols,
  int rows,
  int z, {
  int half = 0,
}) => [
  for (var r = 0; r < rows; r++)
    for (var c = 0; c < cols; c++)
      MjPos((col + c) * 2 + half, (row + r) * 2 + half, z),
];

List<MjPos> _diamond() {
  const lens = [2, 4, 6, 6, 4, 2];
  const starts = [2, 1, 0, 0, 1, 2];
  return [
    for (var r = 0; r < lens.length; r++)
      for (var c = 0; c < lens[r]; c++) MjPos((starts[r] + c) * 2, r * 2, 0),
  ];
}

List<MjPos> _ring() {
  final out = <MjPos>[];
  for (var r = 0; r < 5; r++) {
    for (var c = 0; c < 6; c++) {
      if (r == 0 || r == 4 || c == 0 || c == 5) out.add(MjPos(c * 2, r * 2, 0));
    }
  }
  return [...out, ..._rect(2, 1, 2, 3, 0), ..._rect(2, 2, 2, 1, 1)];
}

List<MjPos> _steps() {
  const heights = [1, 2, 3, 3, 2, 1];
  return [
    for (var row = 0; row < 2; row++)
      for (var c = 0; c < heights.length; c++)
        for (var z = 0; z < heights[c]; z++) MjPos(c * 2, row * 2, z),
  ];
}

